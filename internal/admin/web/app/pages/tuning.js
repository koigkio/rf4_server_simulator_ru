// 鱼获档位对熟练度增量的倍数。1..4 对应 grade 枚举；填 1 表示该档位不加成。
const SKILL_GRADE_KEYS = [
  ['skill_grade_mult_1', 'Незачётная рыба', 'В протоколе grade 1. 1 = без бонуса.'],
  ['skill_grade_mult_2', 'Зачётная рыба', 'В протоколе grade 2, к этой категории относится большинство улова.'],
  ['skill_grade_mult_3', 'Трофейная рыба', 'В протоколе grade 3, то есть «звёздная» рыба.'],
  ['skill_grade_mult_4', 'Рыба с синей короной', 'В протоколе grade 4, сверхредкая.'],
];
let CAT = 'gameplay';

function skillGainModeOf(t) {
  const saved = String(t.skill_gain_mode ?? '');
  if (SKILL_GAIN_MODES.some(([mode]) => mode === saved)) return saved;
  const values = SKILL_GAIN_KEYS.map(([key]) => Number(t[key] ?? 0) || 0);
  if (values.every((v) => v === 0)) return 'native';
  if (values.every((v) => v === 100)) return 'fixed100';
  return 'custom';
}

function skillGainSection(form, t, val, no = 90) {
  const mode = skillGainModeOf(t);
  const pick = async (next) => {
    if (next === mode) return;
    if (form.isDirty() && !(await confirmDialog({ title: 'Есть несохранённые изменения', desc: 'При смене режима вероятности навыков несохранённые значения будут потеряны.', confirm: 'Отменить и переключить' }))) return;
    try {
      await post('/api/skill_gain_mode', { mode: next });
      toast('Вероятность прокачки навыков переключена, вступит в силу примерно через 30 секунд');
      render();
    } catch (e) { toast(errText(e), 'bad'); }
  };
  const buttons = h('div', { class: 'seg', role: 'radiogroup', 'aria-label': 'Режим вероятности прокачки навыков' }, SKILL_GAIN_MODES.map(([key, label]) => h('button', {
    type: 'button', role: 'radio', 'aria-checked': String(key === mode), class: key === mode ? 'on' : '', onclick: () => pick(key),
  }, label)));
  const fields = mode === 'custom' ? h('div', { class: 'stack', style: { marginTop: '14px' } }, SKILL_GAIN_KEYS.map(([key, label, help]) =>
    form.row({ key, label, help, kind: 'float', min: 0, max: 100, unit: '%', def: 0 }, val(key, 0)))) : null;
  // 鱼获档位倍数作为本区块的第二段：它同样按「涨多少」调节熟练度，
  // 和上面的「涨不涨」是同一件事的两个维度，不另起一个区块。
  const gradeFields = SKILL_GRADE_KEYS.map(([key, label, help]) =>
    form.row({ key, label, help, kind: 'float', min: 0, max: 20, unit: '×', def: 1 }, val(key, 1)));
  return pblock(no, 'Вероятность прокачки навыков', 'Переключение всех навыков сразу: как в оригинале, всё 100% или настройка по каждому. 0 = оригинальная формула, 100 = рост гарантирован.',
    [h('div', { class: 'span-2', style: { gridColumn: '1 / -1' } }, buttons,
      h('p', { class: 'hint', style: { margin: '8px 0 0' }, text: 'В режиме 100% каждый подходящий улов, копание или изготовление даёт мастерство; в режиме фиксированного процента поправка счастливого часа к оригинальной вероятности не добавляется.' })),
    ...(fields ? [...fields.childNodes] : []),
    h('div', { class: 'span-2', style: { gridColumn: '1 / -1', marginTop: '14px', paddingTop: '12px', borderTop: '1px solid var(--line)' } },
      h('p', { style: { margin: '0 0 2px', fontWeight: '600' }, text: 'Бонус по категории улова' }),
      h('p', { class: 'hint', style: { margin: '0 0 8px' }, text: 'Чем реже пойманная рыба, тем больше прирост мастерства за раз. Множитель увеличивает только прирост и не меняет вероятность «вырастет ли сейчас» выше; действует в обоих режимах. Базовый прирост 0,1 или 0,2, после умножения округляется до 0,1 — лучше использовать целые множители вроде 1/2/4/8, чтобы 0,15 не округлилось до 0,2. 0 — категория не даёт прироста. У изготовления и копания нет категории рыбы, всегда ×1.' })),
    ...gradeFields], { id: 'pg-skill' });
}

export default async function tuning(params, scope) {
  if (params[0]) {
    const want = OLD_TAB[params[0]] || params[0];
    if (CATS.some(([k]) => k === want)) CAT = want;
  }
  const t = await api('/api/tunables');
  if (!scope.isCurrent()) return [];
  const val = (k, d) => (t[k] === undefined || t[k] === '' ? String(d) : t[k]);
  const form = new Form();
  const event = CAT === 'event' ? eventView(t) : null;
  if (!event) savebar(form, {
    effect:'На сервере вступает в силу не позже чем через 30 секунд.',
    onSave: async (values) => {
      for (const [key, value] of Object.entries(values)) await post('/api/tunables', { key, value: String(value) });
      render();
    },
  });
  const isDirty = event ? event.isDirty : () => form.isDirty();
  scope.setLeaveGuard(isDirty);
  const spec = ([key, label, help, def, kind, unit, min, max]) => ({ key, label, help, def: kind === 'bool' ? String(def) : def, kind, unit, min, max });
  const rows = (list) => list.map((d) => form.row(spec(d), val(d[0], d[3])));

  // 饵效控速未开启时不渲染 pace_* 行：这些参数只在开关打开后才参与计算，
  // 关闭时全部走 legacy/中性通路。
  const paceOn = String(t.bite_pace_enabled ?? '0') === '1';
  const paceVisible = (d) => paceOn || !d[0].startsWith('pace_');
  let body;
  if (event) body = event.blocks;
  else {
    // 一个页签 = 若干主题，每个主题一个 01/02/03… 的 .pblock，页面才不会只有一屏
    const out = [];
    let no = 0;
    for (const key of TAB_GROUPS[CAT] || []) {
      const g = G[key];
      if (!g) continue;
      const advRows = (g.adv || []).filter(paceVisible);
      const mainKids = [
        ...rows(g.main.filter(paceVisible)),
        key === 'bite' && !paceOn
          ? h('p', { class: 'hint', style: { gridColumn: '1 / -1', margin: '4px 0 0' }, text: '«Скорость клёва от наживки» не включена (переключатель — в «Правилах игры → Прочее»): только после включения здесь появятся интервалы ожидания для хорошей/плохой наживки и спиннинга; пока выключено, эти параметры ни на что не влияют.' })
          : null,
        advRows.length
          ? h('div', { class: 'advanced', style: { gridColumn: '1 / -1', marginTop: '6px' } },
            h('p', { class: 'hint', style: { margin: '0 0 2px' } }, 'Дополнительно ', h('small', { text: ` (${advRows.length} шт., обычно менять не нужно)` })),
            h('div', { class: 'two gapped' }, ...rows(advRows)))
          : null,
      ].filter(Boolean);
      out.push(pblock(++no, g.title, g.desc, mainKids, { id: 'pg-' + key }));
      for (const [title, desc, list] of (g.groups || [])) out.push(pblock(++no, title, desc, rows(list), { id: 'pg-' + key + '-' + (out.length + 1) }));
    }
    if (CAT === 'reward') out.push(skillGainSection(form, t, val, ++no));
    body = out;
  }
  const blocks = Array.isArray(body) ? body : [body];
  const tabsEl = pageTabs(CATS, CAT, async (k) => {
    if (k === CAT) return;
    if (event?.busy() || (isDirty() && !(await confirmDialog({ title: 'Есть несохранённые изменения', desc: 'При смене категории эти изменения будут потеряны.', confirm: 'Отменить и переключить' })))) {
      // pageTabs 在点击时先高亮目标；取消后仍应标记实际页签。
      queueMicrotask(() => tabsEl.querySelectorAll('a').forEach((a) => {
        if (a.hash === '#tuning/' + CAT) a.setAttribute('aria-current', 'page'); else a.removeAttribute('aria-current');
      }));
      return;
    }
    CAT = k; replaceHash('#tuning/' + k); render();
  });
  setCrumbTail((CATS.find(([k]) => k === CAT) || [])[1] || '');
  const anchors = blocks.filter((b) => b && b.classList && b.classList.contains('pblock')).map((b) => ({
    id: b.id,
    no: (b.querySelector('.pno') || {}).textContent || '',
    title: b.querySelector('.ptitle > b') ? b.querySelector('.ptitle > b').textContent : '',
    n: b.querySelectorAll('.row').length,
  }));
  const aside = [
    ib('Группы на этой странице', 'Щелчок по названию прокручивает к группе, страница не меняется',
      h('div', { class: 'pills', style: { flexDirection: 'column', alignItems: 'stretch', gap: '6px' } },
        ...anchors.map((a) => h('button', {
          class: 'pill', type: 'button',
          onclick: () => { const el = document.getElementById(a.id); if (el) el.scrollIntoView({ behavior: 'smooth', block: 'start' }); },
        }, h('b', { text: a.no }), h('span', {}, h('span', { text: a.title }), h('em', { style: { display: 'block', fontStyle: 'normal', fontSize: '12.4px', color: 'var(--muted)', marginTop: '2px' }, text: `${a.n} шт.` }))))),
      hint('Прокручивается только основная колонка, адресная строка не меняется — несохранённый черновик не пропадёт.', { margin: '10px 0 0' })),
    ib('Как применяется', null,
      kv([['Область действия', 'Весь сервер'], ['Обновление сервера', 'Не более 30 секунд'], ...(event ? [['Обновление клиента', 'Перезапустить клиент и войти заново']] : [['Изменённые пункты', String(form.dirtyKeys().length)]]), ['Всего параметров', String(Object.keys(t).length)]]),
      h3s('Связанные страницы'),
      h('div', { class: 'pills' }, h('a', { class: 'pill', href: '#hooks/fight', text: 'Параметры вываживания' }))),
  ];
  return [
    pageHead('Параметры игры', TAB_DESC[CAT] || TAB_DESC.gameplay),
    tabsEl,
    work(blocks, aside),
  ];
}
